/**
 * What the wizard will write, decided and PRINTED before anything is touched.
 *
 * 🔴 **THE WIZARD GENERATES GLUE AND KEEPS THE DEPENDENCY.** It writes config, the composition-root
 * wiring and a `.gitignore` line; the telemetry logic stays in a versioned package. That is not
 * timidity — vendoring the logic removes the only upgrade channel there is. A dependency ships a fix
 * to every customer with one version bump; copied-in code ships it through N pull requests that N
 * humans must review, and the end state is documented by Datadog for its own wire protocol: a version
 * skew where *"all traces will be dropped"*, silently. It also makes the instrumentation
 * indistinguishable from first-party code in every SAST scan, SBOM and security review, and turns
 * `npm uninstall` into a reverse codemod.
 *
 * ⛔ **ORDER MATTERS AND IT IS NOT COSMETIC.** The `.gitignore` entry is written BEFORE the file that
 * holds the key. Sentry's wizard does the same thing, and the reason is that a generator which writes
 * a credential into a tracked file has created a secret-in-git incident on the customer's behalf.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { Detection } from "./detect.js";

export interface Write {
  path: string;
  kind: "create" | "append" | "edit";
  contents: string;
  /** Why this file, in the plan output. A write with no stated reason is a write nobody reviewed. */
  why: string;
  /** Written before anything that could contain a secret. */
  priority: number;
}

export interface Plan {
  framework: Detection["framework"];
  evidence: string;
  /** Empty when the project already emits OTLP — the best outcome, and a real one. */
  writes: Write[];
  /** Shell lines the human runs; we never run a package manager for them. */
  commands: string[];
  notes: string[];
}

const GITIGNORE_LINE = ".env.estelle";

function gitignoreWrite(root: string): Write | null {
  const path = join(root, ".gitignore");
  const existing = existsSync(path) ? safeRead(path) : "";
  if (existing.split(/\r?\n/).some((line) => line.trim() === GITIGNORE_LINE)) return null;
  return {
    path: ".gitignore", kind: existsSync(path) ? "append" : "create", priority: 0,
    contents: `${existing && !existing.endsWith("\n") ? "\n" : ""}${GITIGNORE_LINE}\n`,
    why: "so the file holding your monitor key is never committed — written FIRST, before that file exists",
  };
}

function safeRead(path: string): string {
  try { return readFileSync(path, "utf8"); } catch { return ""; }
}

function envWrite(): Write {
  return {
    path: ".env.estelle", kind: "create", priority: 1,
    contents:
      "# Estelle monitoring. Keep this file out of git — the wizard added it to .gitignore.\n" +
      "ESTELLE_ENDPOINT=https://api.fatelabs.ca\n" +
      "ESTELLE_MONITOR_KEY=\n",
    why: "your endpoint and monitor key, in a file the previous step already gitignored",
  };
}

const NODE_GLUE = `// Estelle monitoring. Generated by @fatelabs/estelle-wizard.
//
// The telemetry logic lives in @fatelabs/estelle-agent, a versioned dependency, so a fix reaches you
// with a version bump rather than a pull request. This file is only the wiring, and it is yours to
// edit — re-running the wizard will show you a diff rather than overwrite it.
import { AgentClient } from "@fatelabs/estelle-agent";

export const estelle = new AgentClient({
  // The field is "key", not "apiKey". Read off AgentClientOptions in the SDK, not from memory:
  // this generator emitted apiKey until 2026-10-09, which TypeScript rejects as an excess
  // property and which would leave the client with no credential at all.
  key: process.env.ESTELLE_MONITOR_KEY ?? "",
  endpoint: process.env.ESTELLE_ENDPOINT ?? "https://api.fatelabs.ca",
});
`;

const PY_GLUE = `"""Estelle monitoring. Generated by @fatelabs/estelle-wizard.

The telemetry logic lives in the 'estelle-agent' package, a versioned dependency, so a fix reaches
you with a version bump rather than a pull request. This file is only the wiring, and it is yours to
edit — re-running the wizard shows a diff rather than overwriting it.
"""
import os

from estelle_agent import EstelleAgent

estelle = EstelleAgent(
    # The first argument is "key" and it is REQUIRED. EstelleAgent.__init__ is
    # (self, key, *, repo="", endpoint=...) -- api_key= raised TypeError twice over:
    # an unexpected keyword AND a missing required argument.
    os.environ.get("ESTELLE_MONITOR_KEY", ""),
    endpoint=os.environ.get("ESTELLE_ENDPOINT", "https://api.fatelabs.ca"),
)
`;

export function buildPlan(root: string, detection: Detection, alreadyOtel: boolean): Plan {
  const notes: string[] = [];

  if (alreadyOtel) {
    // ▶ The best outcome the wizard has, and it writes nothing at all.
    return {
      framework: detection.framework, evidence: detection.evidence, writes: [],
      commands: [],
      notes: [
        "This project already emits OpenTelemetry, so it needs no code from Estelle and no package.",
        "Point your existing exporter at us with two environment variables:",
        "    OTEL_EXPORTER_OTLP_ENDPOINT=https://api.fatelabs.ca",
        '    OTEL_EXPORTER_OTLP_HEADERS="authorization=Bearer <your-monitor-key>"',
        "You get spans, logs, metrics, errors and GenAI facts, and errors bind to symbols in your",
        "indexed code graph. Verified end to end against production.",
        "Run `estelle-wizard audit` afterwards to prove a span arrives.",
      ],
    };
  }

  const writes: Write[] = [];
  const gitignore = gitignoreWrite(root);
  if (gitignore) writes.push(gitignore);
  writes.push(envWrite());

  const node = detection.runtime === "node";
  writes.push({
    path: node ? "estelle.instrumentation.ts" : "estelle_instrumentation.py",
    kind: "create", priority: 2,
    contents: node ? NODE_GLUE : PY_GLUE,
    why: "the client, constructed once and exported — import it where you want to report an outcome",
  });

  const commands = node
    ? ["npm install @fatelabs/estelle-agent"]
    : ["pip install estelle-agent"];

  if (detection.wouldEdit.length) {
    notes.push(
      `These files already exist and the wizard will NOT edit them: ${detection.wouldEdit.join(", ")}. ` +
      "Import the generated client from your own entry point instead — a generator editing your " +
      "composition root is the highest-conflict change it can make.",
    );
  }
  if (detection.framework === "unknown") {
    notes.push(
      "No framework matched, so this is the generic wiring. Tell us what you are running and we will " +
      "add a detector — a wizard that guesses is worse than one that says it does not know.",
    );
  }
  notes.push(
    "The three clauses that make Estelle different — subject, outcome, objective — are methods on the " +
    "client. Instrumenting only errors misses them: when an account is banned the event that errors " +
    "is the NEXT call, and everything explaining it sits in events that returned 200.",
  );

  writes.sort((a, b) => a.priority - b.priority);
  return { framework: detection.framework, evidence: detection.evidence, writes, commands, notes };
}
